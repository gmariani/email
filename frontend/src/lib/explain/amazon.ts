export function regionLabel(region: string): string {
    return AWS_REGIONS[region] ?? region;
}

/**
 * SES message ids ("010001a16b87e2b3-26f74ee6-4f88-48cc-8978-de87228e21df-000000")
 * start with "01xx" followed by the send time in milliseconds as 12 hex digits.
 * The same id appears in the Message-ID and in the bounce (Return-Path) address.
 */
export function sesTimestamp(text: string | null | undefined): number | null {
    if (!text) return null;
    const m = /(?:^|[<\s])01[0-9a-f]{2}([0-9a-f]{12})-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}-[0-9a-f]{6}/i.exec(text);
    if (!m) return null;
    const ms = parseInt(m[1], 16);
    // SES launched in 2011; anything outside that range isn't a timestamp.
    return ms > Date.UTC(2011, 0, 1) && ms < Date.now() + 365 * 86_400_000 ? ms : null;
}

export function sesIdFacts(text: string | null | undefined): Fact[] {
    const time = sesTimestamp(text);
    if (time === null) return [];
    const [first, ...rest] = timeFacts('Sent by SES', time);
    return [{ ...first, tone: 'info', hint: 'Decoded from the SES message id: its first 16 hex digits are 01xx followed by the send time in milliseconds.' }, ...rest];
}

/** Feedback-ID: <campaign>:<customer>:<other>:<sender id> (Gmail feedback loop). SES fills it with hashed AWS ids. */
export const feedbackId: Explainer = (field) => {
    const parts = field.value.split(':').map((p) => p.trim());
    const sender = parts[parts.length - 1] ?? '';
    const ids = parts.slice(0, -1);
    const facts: Fact[] = [...fact('Feedback loop sender', sender, { hint: 'The service that receives spam-complaint statistics from Gmail.' })];
    // Positional: Campaign:Customer:Other:SenderId, any of the first three may be empty.
    const labels = ids.length === 3 ? ['Campaign id', 'Customer id', 'Other id'] : ids.map((_, i) => `Identifier ${i + 1}`);
    const ses = /^AmazonSES$/i.test(sender);
    const regions = new Set<string>();

    ids.forEach((id, i) => {
        const m = /^1\.([a-z]{2}(?:-gov)?-[a-z]+-\d)\.(.+)$/.exec(id);
        if (m) regions.add(m[1]);
        facts.push({
            label: labels[i],
            value: id || '(not set)',
            mono: !!id,
            tone: id ? undefined : 'muted',
            hint: ses && m ? `An opaque hash generated by SES in ${m[1]}. It lets Gmail report complaint rates per SES customer without revealing who the customer is.` : undefined,
        });
    });

    if (ses) {
        for (const region of regions) facts.unshift({ label: 'AWS region', value: regionLabel(region), raw: region, tone: 'info' });
        return { summary: `Sent through Amazon SES${regions.size ? ` in ${[...regions].map(regionLabel).join(', ')}` : ''}.`, facts };
    }
    return { facts };
};

/** X-SES-Outgoing: 2026.10.24-54.240.11.162 */
export const sesOutgoing: Explainer = (field) => {
    const m = /^(\d{4})\.(\d{2})\.(\d{2})-([0-9a-f.:]+)$/i.exec(field.value.trim());
    if (!m) return null;
    const [, y, mo, d, ip] = m;
    return {
        summary: `Amazon SES sent this from ${ip} on ${y}-${mo}-${d} (UTC).`,
        facts: [
            ...fact('Sent on (UTC)', `${y}-${mo}-${d}`),
            ...fact('SES outbound IP', ip, { kind: 'ip', hint: 'The SES server that delivered the message to the next hop. Shared by many SES customers unless they rent dedicated IPs.' }),
        ],
    };
};

const VERDICTS: Record<string, [string, 'good' | 'bad' | 'warn' | 'muted']> = {
    PASS: ['Passed', 'good'],
    FAIL: ['Failed', 'bad'],
    GRAY: ['Gray: not clearly spam or not', 'warn'],
    PROCESSING_FAILED: ['Scan failed', 'warn'],
    DISABLED: ['Scanning disabled', 'muted'],
};

/** X-SES-Spam-Verdict / X-SES-Virus-Verdict: added by SES when it *receives* mail. */
export const sesVerdict: Explainer = (field) => {
    const [label, tone] = VERDICTS[field.value.trim().toUpperCase()] ?? [field.value, 'muted'];
    const what = field.key.includes('virus') ? 'virus scan' : 'spam scan';
    return { summary: `SES inbound ${what}: ${label}.`, facts: fact('Verdict', label, { tone }) };
};

export const sesConfigurationSet: Explainer = (field) => ({
    summary: 'The SES configuration set the sender used (it controls tracking, IP pool and event publishing).',
    facts: fact('Configuration set', field.value, { mono: true }),
});

export const sesMessageTags: Explainer = (field) => ({
    summary: 'Tags the sender attached for its own reporting.',
    facts: field.value.split(',').flatMap((tag) => {
        const [k, v] = tag.split('=');
        return fact(k.trim(), v?.trim() ?? '', { mono: true });
    }),
});

export const sesReceipt: Explainer = () => ({
    summary: 'Added when SES receives mail: an encoded record of its spam, virus, SPF and DKIM checks, used to verify the verdict headers weren\'t added by the sender.',
    facts: [],
});

